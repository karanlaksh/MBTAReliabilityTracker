// Generates src/schedule.ts from MBTA's published schedules (V3 API /schedules).
//
//   node scripts/build-schedule.mjs > src/schedule.ts
//
// Committed so the table is reproducible: every number in src/schedule.ts comes
// from this script and the fetch date it records, not from hand-typing.
//
// Scope is the trips the assistant can answer from COLLECTED data: a pair of
// watched stops on one route, in the direction whose destination is watched.
// Of the six watched stops only the three Orange stations form pairs —
// Northeastern is the only Green-E stop, and Route 39's two Huntington Ave stops
// each serve one direction, so no trip runs between them.
//
// Ride:    median over every trip serving both stops in travel order of
//          (arrival at destination - departure from origin), on the weekday date.
// Headway: median gap between consecutive departures from the ORIGIN stop, by the
//          local hour of the earlier departure, for each day type.

const API = 'https://api-v3.mbta.com';
const ROUTE = 'Orange';
const STOPS = ['place-forhl', 'place-rugg', 'place-masta'];
// A representative date of each day type in the current rating, after the
// 2026-11-01 DST change. Check MBTA alerts for a planned diversion before
// changing these: a diversion date would bake shuttle gaps into the table.
const DATES = { weekday: '2026-11-04', saturday: '2026-11-07', sunday: '2026-11-08' };

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
// Seconds since local midnight of the service date, read from the ISO string's own
// local clock (it carries the offset), so a 00:30 next-day time becomes 24:30.
const localSec = (iso, date) => {
  const day = iso.slice(0, 10) === date ? 0 : 86_400;
  return day + Number(iso.slice(11, 13)) * 3600 + Number(iso.slice(14, 16)) * 60 + Number(iso.slice(17, 19));
};

async function fetchDay(date) {
  const url = `${API}/schedules?filter[route]=${ROUTE}&filter[date]=${date}` +
    `&filter[stop]=${STOPS.join(',')}&include=stop`;
  const res = await fetch(url, { headers: process.env.MBTA_API_KEY ? { 'x-api-key': process.env.MBTA_API_KEY } : {} });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const body = await res.json();
  // filter[stop] on a parent station returns its platforms; map each back.
  const parent = Object.fromEntries((body.included ?? [])
    .map((s) => [s.id, s.relationships?.parent_station?.data?.id ?? s.id]));
  return body.data.map((r) => ({
    trip: r.relationships.trip.data.id,
    stop: parent[r.relationships.stop.data.id] ?? r.relationships.stop.data.id,
    dir: r.attributes.direction_id,
    seq: r.attributes.stop_sequence,
    arr: r.attributes.arrival_time && localSec(r.attributes.arrival_time, date),
    dep: r.attributes.departure_time && localSec(r.attributes.departure_time, date),
  }));
}

const fetchedAt = new Date().toISOString();
const ride = {};
const headway = {};
const counts = {};

for (const [dayType, date] of Object.entries(DATES)) {
  const rows = await fetchDay(date);
  const unknown = rows.filter((r) => !STOPS.includes(r.stop));
  if (unknown.length) throw new Error(`unmapped stop ${unknown[0].stop} on ${date}`);
  const trips = {};
  for (const r of rows) (trips[r.trip] ??= []).push(r);
  counts[dayType] = Object.keys(trips).length;

  if (dayType === 'weekday') {
    const samples = {};
    for (const stops of Object.values(trips)) {
      for (const o of stops) for (const d of stops) {
        if (o.seq >= d.seq || o.dep == null || d.arr == null) continue;
        (samples[`${ROUTE}|${o.dir}|${o.stop}|${d.stop}`] ??= []).push(d.arr - o.dep);
      }
    }
    for (const [k, xs] of Object.entries(samples).sort()) ride[k] = median(xs);
  }

  for (const stop of STOPS) for (const dir of [0, 1]) {
    const deps = rows.filter((r) => r.stop === stop && r.dir === dir && r.dep != null).map((r) => r.dep).sort((a, b) => a - b);
    const gaps = {};
    for (let i = 0; i + 1 < deps.length; i++) {
      (gaps[Math.floor(deps[i] / 3600) % 24] ??= []).push((deps[i + 1] - deps[i]) / 60);
    }
    if (!Object.keys(gaps).length) continue; // a terminus has no departures in its arriving direction
    headway[`${ROUTE}|${dir}|${stop}|${dayType}`] = Object.fromEntries(
      Object.entries(gaps).map(([h, xs]) => [h, Math.round(median(xs))]));
  }
}

const lines = [
  '// Generated by scripts/build-schedule.mjs from MBTA\'s published schedules — do not edit by hand.',
  '//',
  `// Source: MBTA V3 API /schedules, route ${ROUTE}, fetched ${fetchedAt}.`,
  `//   Dates: weekday ${DATES.weekday} (${counts.weekday} trips), Saturday ${DATES.saturday} (${counts.saturday}),`,
  `//   Sunday ${DATES.sunday} (${counts.sunday}).`,
  '//   Ride times: median scheduled time between each pair of stops, weekday, every trip',
  '//     serving both stops, in travel order.',
  '//   Headways: median scheduled gap between consecutive departures from the origin stop,',
  '//     by local hour.',
  '// Only Orange pairs exist: see the header of scripts/build-schedule.mjs for why.',
  '// Used by src/ask.ts to compute a platform-by time; never by the model.',
  '',
  '/** Scheduled in-vehicle seconds, keyed `route|direction|fromStop|toStop`. A trip is answerable only if its key is here. */',
  `export const RIDE_SEC: Record<string, number> = ${JSON.stringify(ride, null, 2)};`,
  '',
  '/** Scheduled minutes between departures, keyed `route|direction|originStop|weekday|saturday|sunday`, then local hour. */',
  `export const HEADWAY_MIN: Record<string, Record<number, number>> = ${JSON.stringify(headway, null, 2)};`,
  '',
];
process.stdout.write(lines.join('\n'));
